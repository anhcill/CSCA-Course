    let r=await invoke(assignments,"get","/:assignmentId",{user:student,params:{assignmentId:assignment.id}});
    assert.equal(r.statusCode,200,JSON.stringify(r.body));
    r=await invoke(assignments,"put","/teacher/accommodations",{user:teacher,body:{assessmentType:"assignment",assessmentId:assignment.id,userId:student.id,dueAt:new Date(Date.now()+72*3600000).toISOString(),extraTimeMinutes:0,reason:"Verified learner deadline accommodation"}});
