test("gradebook policy distinguishes missing grades, actual zero and quiz attempt strategy", () => {
  const policy=normalizeGradebookPolicy({weights:{assignment:50,quiz:40,attendance:10},quizStrategy:"best",missingPolicy:"exclude",passMark:60});
  assert.equal(calculateGradebookTotal({assignment:[100,null,0],quiz:[],attendance:[]},policy).total,50);
  assert.equal(calculateGradebookTotal({assignment:[100,null,0]}, {...policy,missingPolicy:"zero"}).total,33.33);
  assert.equal(calculateGradebookTotal({},policy).total,null);
  const attempts=[{id:1,attempt_number:1,score:9,max_score:10},{id:2,attempt_number:2,score:20,max_score:100}];
  assert.equal(aggregateQuizAttempts(attempts,"best"),90);
  assert.equal(aggregateQuizAttempts(attempts,"latest"),20);
  assert.equal(aggregateQuizAttempts(attempts,"average"),55);
  assert.throws(()=>normalizeGradebookPolicy({...policy,weights:{assignment:40,quiz:40,attendance:10}}));
  assert.throws(()=>normalizeAnnotations([{page:1,text:"bad",x:2,y:0.5}]));
  assert.equal(canResubmit({return_requested:true,resubmit_until:"2020-01-01"}),false);
});

